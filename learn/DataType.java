// 章节: 数据类型
package learn;

public class DataType {
  public static void main(String[] args) {
    // 基本类型(8种)
    // 整型
    byte a = 1;
    short b = 1;
    int c = 1;
    long d = 1l;

    // 浮点型
    float e = 0.1f;
    double f = 0.1;

    // 布尔型
    boolean g = true;

    // 字符型
    char h = 'a';

    // 包装类型(8种一一对应)
    Byte i = 1;
    Short j = 1;
    Integer k = 1;
    Long l = 1l;
    Float m = 0.1f;
    Double o = 0.1;
    Boolean p = false;
    Character q = 'a';
  }
}
